def extract_chinese_locations(text: str) -> list[dict]:
    """Extract Chinese province and city names from arbitrary text.

    Used to parse location hints from reverse image search results,
    search snippets, and other unstructured text sources.

    Args:
        text: Arbitrary text that may contain Chinese location names.

    Returns:
        List of dicts like [{"name": "杭州", "type": "city", "province": "浙江省"}, ...]
        sorted by specificity (cities before provinces).
    """
    if not text:
        return []

    found: list[dict] = []
    seen: set[str] = set()

    # Match cities (longer names first to avoid partial matches)
    for city in sorted(_CITY_NAMES, key=len, reverse=True):
        if city in text and city not in seen:
            seen.add(city)
            clean = city.rstrip("市")
            province = _CITY_TO_PROVINCE.get(clean, "")
            found.append({
                "name": clean,
                "type": "city",
                "province": province,
            })

    # Match province full names
    for prov in sorted(_PROVINCE_FULL_NAMES, key=len, reverse=True):
        if prov in text:
            short = prov.rstrip("省").rstrip("市").replace("壮族自治区", "").replace("回族自治区", "").replace("维吾尔自治区", "").replace("自治区", "")
            if short not in seen:
                seen.add(short)
                found.append({
                    "name": short,
                    "type": "province",
                    "province": prov,
                })

    # Match province short names (only if not already found via city)
    for prov in _PROVINCE_SHORT_NAMES:
        if prov in text and prov not in seen:
            seen.add(prov)
            found.append({
                "name": prov,
                "type": "province",
                "province": _SHORT_TO_FULL.get(prov, prov),
            })

    # Cities before provinces (more specific)
    found.sort(key=lambda x: 0 if x["type"] == "city" else 1)
    return found


def extract_locations_from_reverse_search(results: list[dict]) -> list[dict]:
    """Extract location entities from reverse image search results.

    Parses titles, snippets, and URLs from multi-engine reverse image
    search to find geographic hints. Useful for cross-referencing with
    CLIP+FAISS and hypothesis scoring.

    Args:
        results: List of search result dicts with 'title', 'snippet', 'url' keys.

    Returns:
        List of unique location dicts found across all results.
    """
    all_text_parts: list[str] = []
    for r in (results or []):
        all_text_parts.append(r.get("title", ""))
        all_text_parts.append(r.get("snippet", ""))
        # Extract domain as potential location hint (e.g., hangzhou.xxx.com)
        url = r.get("url", "")
        if url:
            from urllib.parse import urlparse
            try:
                parsed = urlparse(url)
                domain = parsed.netloc
                # Replace common TLD separators
                domain = domain.replace(".com", " ").replace(".cn", " ").replace(".org", " ")
                domain = domain.replace(".net", " ").replace(".gov", " ").replace(".edu", " ")
                all_text_parts.append(domain)
            except Exception:
                pass

    combined = " ".join(all_text_parts)
    return extract_chinese_locations(combined)


