def build_initial_hypotheses(clues: dict, ocr_data: dict | None,
                             search_strategy: dict,
                             geoclip_result: dict | None = None,
                             clip_result: dict | None = None) -> list[dict]:
    """Build initial hypotheses with scores from clue weights (方案一).

    Each hypothesis has:
      - province, city (optional)
      - score: 0.0-1.0
      - supporting_evidence: list of {clue, weight}
      - source: where this hypothesis came from
    """
    weights = get_clue_reliability_weights()
    candidates = search_strategy.get("candidate_provinces", [])
    primary_region = search_strategy.get("primary_region")
    ocr_province = None
    ocr_city = None

    # Extract definitive location from OCR
    if ocr_data:
        plates = ocr_data.get("license_plates", [])
        if plates:
            ocr_province = plates[0].get("province", "")
            ocr_city = plates[0].get("city", "")
            if ocr_city == "未知":
                ocr_city = None
        if not ocr_province:
            phones = ocr_data.get("phone_area_codes", [])
            if phones:
                ocr_province = phones[0].get("province", "")
                ocr_city = phones[0].get("city", "")
                if ocr_city == "未知":
                    ocr_city = None

    # If OCR gives a definitive province, start there
    if ocr_province and ocr_province != "未知":
        initial_score = weights["license_plate"]["weight"] if ocr_data and ocr_data.get("license_plates") else weights["phone_area_code"]["weight"]
        return [{
            "province": ocr_province,
            "city": ocr_city,
            "score": initial_score,
            "supporting_evidence": [
                {"clue": f"车牌指向{ocr_province}", "weight": initial_score}
            ] if ocr_data and ocr_data.get("license_plates") else [
                {"clue": f"电话区号指向{ocr_province}", "weight": initial_score}
            ],
            "contradicting_evidence": [],
            "source": "ocr_definitive",
            "round_created": 0,
        }]

    # Otherwise, score each candidate province based on clue matches
    hypotheses = []
    for province in candidates:
        score = 0.0
        evidence = []

        # Match vegetation
        veg = clues.get("vegetation", [])
        veg_str = " ".join(veg) if veg else ""
        for vr in VEGETATION_RANGES:
            if "provinces" in vr and province in vr["provinces"]:
                if any(kw in veg_str for kw in vr.get("keywords", [])):
                    score += weights["vegetation_type"]["weight"]
                    evidence.append({
                        "clue": f"植被匹配: {vr['plant']}分布在{province}",
                        "weight": weights["vegetation_type"]["weight"],
                    })

        # Match architecture
        arch = clues.get("architecture", "")
        for af in ARCHITECTURE_FINGERPRINTS:
            if province in af.get("provinces", []):
                if any(kw in arch for kw in af.get("keywords", [])):
                    score += weights["distinctive_architecture"]["weight"]
                    evidence.append({
                        "clue": f"建筑匹配: {af['style']}分布在{province}",
                        "weight": weights["distinctive_architecture"]["weight"],
                    })

        # Match script
        scripts = clues.get("script", [])
        for rule in get_china_script_region_rules():
            if rule["script"] in scripts and province in rule["expected_provinces"]:
                score += weights["minority_script"]["weight"]
                evidence.append({
                    "clue": f"文字匹配: {rule['script']}分布在{province}",
                    "weight": weights["minority_script"]["weight"],
                })

        # GeoCLIP probability boost: weight scaled by model probability
        if geoclip_result and geoclip_result.get("top_provinces"):
            for pred in geoclip_result["top_provinces"]:
                pred_province = normalize_province_name(pred.get("province", ""))
                if pred_province and pred_province == province:
                    prob = pred.get("probability", 0)
                    geo_bonus = round(0.30 * prob, 3)  # max 0.30 if prob=1.0
                    score += geo_bonus
                    evidence.append({
                        "clue": f"GeoCLIP预测: {province}(prob={prob:.4f})",
                        "weight": geo_bonus,
                    })
                    break

        # CLIP similarity boost (only when database has results)
        if clip_result and clip_result.get("top_provinces"):
            for pred in clip_result["top_provinces"]:
                pred_province = normalize_province_name(pred.get("province", ""))
                if pred_province and pred_province == province:
                    similarity = float(pred.get("similarity", 0.0) or 0.0)
                    # IP over normalized vectors is cosine similarity. This is
                    # a ranking signal, not a calibrated probability.
                    clip_bonus = round(0.15 * max(0.0, min(1.0, similarity)), 3)
                    score += clip_bonus
                    evidence.append({
                        "clue": f"CLIP相似: {province}(similarity={similarity:.3f})",
                        "weight": clip_bonus,
                    })
                    break

        # Boost if in primary region
        if primary_region and province in get_provinces_for_region(primary_region):
            score += 0.10
            evidence.append({
                "clue": f"宏观区域匹配: {primary_region}",
                "weight": 0.10,
            })

        if evidence:
            # Normalize score to 0-1 range
            score = min(score, 0.85)
            hypotheses.append({
                "province": province,
                "city": None,
                "score": round(score, 3),
                "supporting_evidence": evidence,
                "contradicting_evidence": [],
                "source": "clue_matching",
                "round_created": 0,
            })

    # Sort by score descending, keep top 5
    hypotheses.sort(key=lambda h: h["score"], reverse=True)
    hypotheses = hypotheses[:5]

    # If no hypotheses from clue matching, seed with primary region provinces
    if not hypotheses and primary_region:
        region_provinces = get_provinces_for_region(primary_region)[:4]
        for p in region_provinces:
            hypotheses.append({
                "province": p,
                "city": None,
                "score": 0.15,
                "supporting_evidence": [
                    {"clue": f"宏观区域({primary_region})候选", "weight": 0.10}
                ],
                "contradicting_evidence": [],
                "source": "region_seed",
                "round_created": 0,
            })

    return hypotheses


def update_hypothesis_score(hypothesis: dict, tool_result: dict,
                            is_supporting: bool, round_num: int,
                            tool_name: str = "") -> dict:
    """Update a hypothesis score based on tool result (方案一)."""
    # geocode/reverse_geocode from Amap have highest precision → bigger bump
    if tool_name in ("geocode", "reverse_geocode", "search_nearby"):
        bump_factor = 0.40
        penalty_factor = 0.30
    else:
        bump_factor = 0.25
        penalty_factor = 0.40

    if is_supporting:
        # Diminishing returns on supporting evidence
        hypothesis["score"] = min(
            hypothesis["score"] + (1.0 - hypothesis["score"]) * bump_factor,
            0.92,
        )
        hypothesis["supporting_evidence"].append({
            "clue": f"工具验证通过(第{round_num}轮)",
            "weight": bump_factor,
        })
    else:
        # Penalty for contradiction
        hypothesis["score"] *= penalty_factor
        hypothesis["contradicting_evidence"].append({
            "clue": f"工具结果矛盾(第{round_num}轮)",
            "weight": -0.3,
        })
    hypothesis["score"] = round(hypothesis["score"], 3)
    return hypothesis


