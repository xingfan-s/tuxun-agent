def get_city_fingerprint(city_name: str) -> dict | None:
    """Look up visual fingerprint for a given city name."""
    clean = city_name.rstrip("市省")
    for cf in CITY_FINGERPRINTS:
        if cf["city"] == clean or cf["city"] in clean or clean in cf["city"]:
            return cf
    return None


def match_city_features(clue_text: str, city_name: str) -> tuple[int, list[str]]:
    """Count how many city-specific features match the clue text.

    Args:
        clue_text: Combined text from vision analysis, clues, OCR etc.
        city_name: City to check against.

    Returns:
        (match_count, [matched_keywords])
    """
    cf = get_city_fingerprint(city_name)
    if not cf:
        return 0, []

    matched = []
    for kw in cf.get("keywords", []):
        if kw in clue_text:
            matched.append(kw)

    return len(matched), matched


def get_city_confusables(city_name: str) -> list[str]:
    """Get list of visually confusable cities for a given city."""
    cf = get_city_fingerprint(city_name)
    if not cf:
        return []
    return cf.get("confusable", [])
