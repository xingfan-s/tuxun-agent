def normalize_province_name(name: str) -> str:
    """Convert province name from any format to standard Chinese short form.

    e.g., 'Guangdong Sheng' → '广东',
          'guangdong' → '广东',
          '广东省' → '广东',
          'Guangdong' → '广东'
    """
    if not name:
        return ""
    # Strip "省", "市", "自治区", "sheng", "shi" suffixes
    cleaned = name.rstrip("省市自治区").strip()
    cleaned_lower = cleaned.lower()
    if cleaned_lower in _EN_TO_CN_PROVINCE:
        return _EN_TO_CN_PROVINCE[cleaned_lower]
    # Also check without suffix handling
    for suffix in (" sheng", " shi", " zizhiqu", " huizu zizhiqu",
                   " uygur zizhiqu", " zhuangzu zizhiqu"):
        if cleaned_lower.endswith(suffix):
            short = cleaned_lower[:-len(suffix)]
            if short in _EN_TO_CN_PROVINCE:
                return _EN_TO_CN_PROVINCE[short]
    return cleaned


def contains_province(text: str, target_provinces: list[str]) -> bool:
    """Check if any target province name appears in text (Chinese or English)."""
    if not text:
        return False
    text_lower = text.lower()
    for p in target_provinces:
        if p in text:
            return True
        # Also check English names
        for en_name, cn_name in _EN_TO_CN_PROVINCE.items():
            if cn_name == p and en_name.lower() in text_lower:
                return True
    return False


